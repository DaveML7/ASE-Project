"""Generate db/app-access.sql (roles and grants) from the db-manager access policy.

    python tools/build_db_access.py

The policy in services/db_manager/dbmanager/policy.py is the single source: it decides what
the application allows AND what the database grants, so the two cannot drift apart. CI fails
if the committed file differs from this output.
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "services" / "db_manager"))

from dbmanager.policy import ACCESS, CALLERS, DEDICATED_RIGHTS, TABLES, role_for  # noqa: E402

LOGIN_ROLE = "monster_tamers_app"
SERIAL_TABLES = {t for t in TABLES if t != "players"}  # every other table has a bigserial id
SCHEMAS = sorted({spec.schema for spec in TABLES.values()})
LEGACY_TABLES = sorted(TABLES)  # earlier versions kept every table in `public`


def rights(caller: str) -> dict[str, set[str]]:
    merged: dict[str, set[str]] = {}
    for source in (ACCESS, DEDICATED_RIGHTS):
        for table, actions in source.get(caller, {}).items():
            merged.setdefault(table, set()).update(actions)
    return merged


def grants(caller: str) -> list[str]:
    role, lines = role_for(caller), []
    for table, actions in sorted(rights(caller).items()):
        spec, ref = TABLES[table], f"{TABLES[table].schema}.{table}"
        full_select = bool(actions & {"select", "insert", "update", "delete"})
        if full_select:  # INSERT/UPDATE ... RETURNING * and WHERE clauses need SELECT
            lines.append(f"GRANT SELECT ON {ref} TO {role};")
        if "insert" in actions:
            lines.append(f"GRANT INSERT ({', '.join(sorted(spec.writable))}) ON {ref} TO {role};")
            if table in SERIAL_TABLES:
                lines.append(f"GRANT USAGE ON SEQUENCE {ref}_id_seq TO {role};")
        if "update" in actions:
            lines.append(f"GRANT UPDATE ({', '.join(sorted(spec.updatable))}) ON {ref} TO {role};")
        if "increment" in actions:
            lines.append(
                f"GRANT UPDATE ({', '.join(sorted(spec.incrementable))}) ON {ref} TO {role};"
            )
            if not full_select:
                lines.append(
                    f"GRANT SELECT ({', '.join(spec.returned_on_increment)}) ON {ref} TO {role};"
                )
        if "delete" in actions:
            lines.append(f"GRANT DELETE ON {ref} TO {role};")
    schemas = sorted({TABLES[t].schema for t in rights(caller)})
    return [f"GRANT USAGE ON SCHEMA {', '.join(schemas)} TO {role};", *lines]


def build() -> str:
    out = [
        "-- GENERATED by tools/build_db_access.py from services/db_manager/dbmanager/policy.py.",
        "-- Do not edit: change the policy and run the generator. Safe to run on fresh and on",
        "-- existing databases (every statement is idempotent).",
        "",
        "-- 1. One schema per microservice. Databases created by earlier versions kept every",
        "--    table in `public`: move them (a no-op on fresh databases).",
    ]
    out += [f"CREATE SCHEMA IF NOT EXISTS {schema};" for schema in SCHEMAS]
    out += [
        f"ALTER TABLE IF EXISTS public.{table} SET SCHEMA {TABLES[table].schema};"
        for table in LEGACY_TABLES
    ]
    out += [
        "ALTER TABLE auth_data.credentials ADD COLUMN IF NOT EXISTS registration_complete boolean",
        "    NOT NULL DEFAULT true;  -- keep existing accounts active",
        "",
        "-- 2. The login role of the db-manager. It owns NO table right itself.",
        "\\getenv db_app_password DB_APP_PASSWORD",
        "SET password_encryption = 'scram-sha-256';",
        f"SELECT 'CREATE ROLE {LOGIN_ROLE} LOGIN'",
        f"WHERE NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '{LOGIN_ROLE}') \\gexec",
        f"ALTER ROLE {LOGIN_ROLE} WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION",
        "    NOBYPASSRLS PASSWORD :'db_app_password';",
        "",
        "-- 3. Nobody gets anything by default.",
        "REVOKE CREATE ON SCHEMA public FROM PUBLIC;",
        f"REVOKE ALL ON ALL TABLES IN SCHEMA public FROM {LOGIN_ROLE};",
    ]
    for schema in SCHEMAS:
        out += [
            f"REVOKE ALL ON SCHEMA {schema} FROM PUBLIC;",
            f"REVOKE ALL ON ALL TABLES IN SCHEMA {schema} FROM PUBLIC, {LOGIN_ROLE};",
            f"REVOKE ALL ON ALL SEQUENCES IN SCHEMA {schema} FROM PUBLIC, {LOGIN_ROLE};",
        ]
    out += [
        "",
        "-- 4. One role per service. The login role may only SWITCH to them (no inherited rights).",
    ]
    for caller in CALLERS:
        role = role_for(caller)
        out += [
            f"SELECT 'CREATE ROLE {role} NOLOGIN'",
            f"WHERE NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '{role}') \\gexec",
            f"REVOKE ALL ON SCHEMA {', '.join(SCHEMAS)} FROM {role};",
            f"REVOKE ALL ON ALL TABLES IN SCHEMA {', '.join(SCHEMAS)} FROM {role};",
            f"REVOKE ALL ON ALL SEQUENCES IN SCHEMA {', '.join(SCHEMAS)} FROM {role};",
            f"GRANT {role} TO {LOGIN_ROLE} WITH INHERIT FALSE, SET TRUE;",
        ]
    out += ["", "-- 5. What each service role may do (derived from the access policy)."]
    for caller in CALLERS:
        out += ["", f"-- {caller}", *grants(caller)]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    (ROOT / "db" / "app-access.sql").write_text(build())
