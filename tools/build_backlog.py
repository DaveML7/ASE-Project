"""Build the completed project backlog from one data table.

    python tools/build_backlog.py

Writes docs/backlog.md and docs/Monster_Tamers_Backlog_completed.xlsx (the course
spreadsheet plus a "Completed backlog" sheet). Every row was checked against the
code; the "Verified by" column names the automated test that proves it, so the
claim can be re-run at any time (see README, "Tests").
"""

import datetime
import io
import pathlib
import re
import zipfile

import openpyxl
from openpyxl.styles import Alignment, Font, PatternFill

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs" / "requirements" / "Monster_Tamers_Backlog.xlsx"


# id, phase, title, acceptance criteria (Given/When/Then), dependencies, implemented by, verified by, status
from backlog_data import NOT_DONE, STORIES, O  # noqa: E402


def markdown() -> str:
    lines = [
        "# Project backlog",
        "",
        "Completed backlog of the *Monster Tamers* project: every mandatory (red and yellow)",
        "story has verifiable acceptance criteria in Given/When/Then form, its dependencies",
        "(prerequisite stories by id) and the automated tests that prove it. Generated by",
        "`tools/build_backlog.py` from a single data table; a spreadsheet version is in",
        "`docs/Monster_Tamers_Backlog_completed.xlsx`.",
        "",
        "How to re-run the evidence: see *Tests* in the README (unit tests, Newman component,",
        "integration and acceptance collections, concurrency test).",
        "",
        "| ID | Phase | Story | Dependencies | Status |",
        "| --- | --- | --- | --- | --- |",
    ]
    for sid, phase, title, _, deps, _, _, status in STORIES:
        lines.append(f"| {sid} | {phase} | {title} | {deps} | {status} |")
    lines += ["", "## Acceptance criteria", ""]
    for sid, phase, title, criteria, deps, impl, tests, status in STORIES:
        lines += [f"### {sid} - {title}", "", f"*{phase}* - **{status}**", ""]
        lines += [f"- {criterion}" for criterion in criteria]
        lines += [
            "",
            f"- **Dependencies:** {deps}",
            f"- **Implemented by:** {impl}",
            f"- **Verified by:** {tests}",
            "",
        ]
    lines += ["## Optional stories not implemented", ""]
    lines += [f"- {sid} - {title}" for sid, title in NOT_DONE.items()]
    lines.append("")
    return "\n".join(lines)


def workbook() -> openpyxl.Workbook:
    book = openpyxl.load_workbook(SOURCE)
    if "Completed backlog" in book.sheetnames:
        del book["Completed backlog"]
    sheet = book.create_sheet("Completed backlog", 1)
    header = [
        "ID",
        "Phase",
        "Story",
        "Acceptance criteria (Given / When / Then)",
        "Dependencies",
        "Implemented by",
        "Verified by",
        "Status",
    ]
    sheet.append(header)
    for sid, phase, title, criteria, deps, impl, tests, status in STORIES:
        sheet.append(
            [sid, phase, title, "\n".join(f"- {c}" for c in criteria), deps, impl, tests, status]
        )
    for sid, title in NOT_DONE.items():
        sheet.append([sid, O, title, "", "", "", "", "Not implemented"])
    fill = PatternFill("solid", fgColor="1F3864")
    for cell in sheet[1]:
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = fill
    for column, width in zip("ABCDEFGH", (8, 18, 36, 90, 20, 40, 50, 26)):
        sheet.column_dimensions[column].width = width
    for row in sheet.iter_rows(min_row=2):
        for cell in row:
            cell.alignment = Alignment(wrap_text=True, vertical="top")
    sheet.freeze_panes = "A2"
    return book


def save_reproducible(book: openpyxl.Workbook, path: pathlib.Path) -> None:
    """Write the workbook with fixed timestamps so the same data gives the same bytes."""
    fixed = datetime.datetime(2026, 1, 1)
    book.properties.created = book.properties.modified = fixed
    buffer = io.BytesIO()
    book.save(buffer)
    with (
        zipfile.ZipFile(buffer) as source,
        zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as target,
    ):
        for name in sorted(source.namelist()):
            info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o600 << 16
            data = source.read(name)
            if name == "docProps/core.xml":  # openpyxl stamps "now" while saving
                data = re.sub(
                    rb"(<dcterms:(?:created|modified)[^>]*>)[^<]*(</)",
                    rb"\g<1>2026-01-01T00:00:00Z\g<2>",
                    data,
                )
            target.writestr(info, data)


def main() -> None:
    (ROOT / "docs" / "backlog.md").write_text(markdown())
    save_reproducible(workbook(), ROOT / "docs" / "Monster_Tamers_Backlog_completed.xlsx")


if __name__ == "__main__":
    main()
